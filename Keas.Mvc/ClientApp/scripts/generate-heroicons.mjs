import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import * as icons from '@heroicons/react/24/outline/index.js';
import * as solidIcons from '@heroicons/react/24/solid/index.js';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const names = JSON.parse(readFileSync(new URL('./heroicons.json', import.meta.url)));
const viewsRoot = fileURLToPath(new URL('../../Views/', import.meta.url));
for (const file of readdirSync(viewsRoot, { recursive: true })) {
  if (!file.endsWith('.cshtml')) continue;
  const view = readFileSync(join(viewsRoot, file), 'utf8');
  for (const match of view.matchAll(/<hero-icon\b[^>]*\bname\s*=\s*["']([a-z][a-z0-9-]*)["']/g)) {
    if (!Object.hasOwn(names, match[1])) {
      throw new Error(`Unregistered Razor Heroicon "${match[1]}" in ${file}. Add it to scripts/heroicons.json.`);
    }
  }
}

const license = readFileSync(new URL('../node_modules/@heroicons/react/LICENSE', import.meta.url), 'utf8').trim();
const generateEntries = (collection) => Object.entries(names).map(([name, component]) => {
  if (!collection[component]) throw new Error(`Unknown Heroicon: ${component}`);
  const svg = renderToStaticMarkup(createElement(collection[component]));
  const paths = svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>$/, '');
  return `            ["${name}"] = """${paths}"""`;
});
const entries = generateEntries(icons);
const solidEntries = generateEntries(solidIcons);
const output = `// Generated by ClientApp/scripts/generate-heroicons.mjs from @heroicons/react.
// Regenerate with npm run icons:generate. Do not edit the paths by hand.
/*
${license}
*/
using System.Collections.Generic;

namespace Keas.Mvc.TagHelpers
{
    internal static class HeroIconPaths
    {
        internal static readonly IReadOnlyDictionary<string, string> All = new Dictionary<string, string>
        {
${entries.join(',\n')}
        };

        internal static readonly IReadOnlyDictionary<string, string> Solid = new Dictionary<string, string>
        {
${solidEntries.join(',\n')}
        };
    }
}
`;
const target = new URL('../../TagHelpers/HeroIconPaths.g.cs', import.meta.url);
let existing;
try { existing = readFileSync(target, 'utf8'); } catch { /* First generation. */ }
if (existing !== output) writeFileSync(target, output);
console.log(`Verified ${entries.length} Razor Heroicons.`);
