import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import * as icons from '@heroicons/react/24/outline/index.js';
import { readFileSync, writeFileSync } from 'node:fs';

const names = JSON.parse(readFileSync(new URL('./heroicons.json', import.meta.url)));
const license = readFileSync(new URL('../node_modules/@heroicons/react/LICENSE', import.meta.url), 'utf8').trim();
const entries = Object.entries(names).map(([name, component]) => {
  if (!icons[component]) throw new Error(`Unknown Heroicon: ${component}`);
  const svg = renderToStaticMarkup(createElement(icons[component]));
  const paths = svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>$/, '');
  return `            ["${name}"] = """${paths}"""`;
});
const output = `// Generated by ClientApp/scripts/generate-heroicons.mjs from @heroicons/react.
// Regenerate with npm run icons:generate. Do not edit the paths by hand.
/*
${license}
*/
using System.Collections.Generic;

namespace Keas.Mvc.TagHelpers
{
    internal static class HeroIconPaths
    {
        internal static readonly IReadOnlyDictionary<string, string> All = new Dictionary<string, string>
        {
${entries.join(',\n')}
        };
    }
}
`;
const target = new URL('../../TagHelpers/HeroIconPaths.g.cs', import.meta.url);
let existing;
try { existing = readFileSync(target, 'utf8'); } catch { /* First generation. */ }
if (existing !== output) writeFileSync(target, output);
console.log(`Verified ${entries.length} Razor Heroicons.`);
